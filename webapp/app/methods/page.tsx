"use client";
import { ErrorBox, Loading } from "@/components/Bits";
import { IconDownload } from "@/components/Icons";
import { Footer } from "@/components/Shell";
import { dataUrl, useRiver } from "@/lib/data";
import { fmtDate } from "@/lib/format";

export default function Methods() {
  const { data, error } = useRiver();
  if (error) return <ErrorBox error={error} />;
  if (!data) return <Loading />;
  const m = data.manifest;
  const rows: [string, string][] = [
    ["Data", `NASA-ISRO NISAR L2 GCOV, ${m.passes.length} passes, ${fmtDate(m.passes[0].date)} – ${fmtDate(m.passes[m.passes.length - 1].date, true)}. Provisional.`],
    ["Pixel size", `${m.pixel_m} m (shown at ${m.pixel_m * m.display_step} m on the map)`],
    ...Object.entries(m.method).map(([k, v]) => [k.replace(/_/g, " "), String(v)] as [string, string]),
    ["Counted as lost", m.lost_rule],
    ["Homes", `${m.homes_source}, within ${m.method.near_m ?? 200} m of the new bank`],
    ["Generated", new Date(m.generated_utc).toUTCString()],
  ];
  return (
    <>
      <main className="page">
        <div className="page-head">
          <div><h2>Methods and data</h2><p>Every number in this app comes from tested Python code in the open repository. Nothing on screen is generated by AI.</p></div>
          <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
            <a className="btn" href={dataUrl(m.files.segments)} download><IconDownload /> Stretches (GeoJSON)</a>
            <a className="btn" href={dataUrl(m.files.csv)} download><IconDownload /> CSV</a>
            <a className="btn" href={dataUrl("manifest.json")} download><IconDownload /> Manifest</a>
          </div>
        </div>
        <div className="grid g-2">
          <div className="card">
            <h3>How a pass becomes a warning</h3>
            <ol className="steps" style={{ marginTop: 12 }}>
              <li><span><b>Read the radar</b><span className="muted">HH backscatter for our box only, read straight from the NISAR file at NASA ASF.</span></span></li>
              <li><span><b>Map water</b><span className="muted">Speckle filter, then a per-pass dB threshold from the histogram valley.</span></span></li>
              <li><span><b>Find the outer banks</b><span className="muted">The main river only; sandbars inside the river and thin creeks are ignored.</span></span></li>
              <li><span><b>Measure movement</b><span className="muted">Median movement per 500 m stretch; stretches where the bank jumps to another channel are skipped.</span></span></li>
              <li><span><b>Score and rank</b><span className="muted">Red: moved ≥ 100 m with homes within 200 m. Amber: moved ≥ 30 m.</span></span></li>
              <li><span><b>Alert</b><span className="muted">Fixed Bangla and English templates filled with the numbers.</span></span></li>
            </ol>
          </div>
          <div className="card">
            <h3>Limits we state openly</h3>
            <ul style={{ margin: "8px 0 0", paddingLeft: 18 }}>
              <li>NISAR science data is still provisional.</li>
              <li>{m.segments?.jump ?? 0} of {(m.segments?.ok ?? 0) + (m.segments?.jump ?? 0) + (m.segments?.gap ?? 0)} stretches were skipped because the bank switched channel.</li>
              <li>The smallest movement we can see is about two pixels (20 m).</li>
              <li>The risk thresholds are not yet tested against 2026 reports (the back-test comes next).</li>
              <li>Building footprints are open data and miss some homes.</li>
            </ul>
          </div>
        </div>
        <div className="card" style={{ marginTop: 16 }}>
          <h3>Settings of this run</h3>
          <div className="table-wrap" style={{ marginTop: 10 }}>
            <table className="data" style={{ minWidth: 0 }}><tbody>
              {rows.map(([k, v]) => <tr key={k}><td className="muted" style={{ textTransform: "capitalize", width: 190, verticalAlign: "top" }}>{k}</td><td style={{ whiteSpace: "normal" }}>{v}</td></tr>)}
            </tbody></table>
          </div>
        </div>
        <div className="card" style={{ marginTop: 16 }}>
          <h3>Passes and thresholds</h3>
          <div className="table-wrap" style={{ marginTop: 10 }}>
            <table className="data"><thead><tr><th>Date</th><th>Threshold</th><th>From</th><th>Water</th><th>Granule</th></tr></thead><tbody>
              {m.passes.map((p) => <tr key={p.date}><td>{fmtDate(p.date, true)}</td><td className="num">{p.threshold_db} dB</td><td>{p.threshold_from}</td><td className="num">{p.water_km2} km²</td><td style={{ fontSize: 11.5 }}>{p.granule}</td></tr>)}
            </tbody></table>
          </div>
        </div>
        <div className="card" style={{ marginTop: 16 }}>
          <h3>Sources and credits</h3>
          <ul style={{ margin: "8px 0 0", paddingLeft: 18 }}>
            <li>Radar: NASA-ISRO NISAR L2 GCOV, via NASA Alaska Satellite Facility DAAC (provisional).</li>
            <li>Homes: Overture Maps buildings (OpenStreetMap contributors, Google Open Buildings, Microsoft).</li>
            <li>Basemaps: Esri World Imagery; Sentinel-2 cloudless 2025 by EOX (CC BY-NC-SA 4.0); Esri World Topographic, World Street Map, Dark Gray Canvas and World Boundaries and Places labels (with OpenStreetMap data); Mapzen terrain tiles (AWS Open Data).</li>
            <li>Software: Next.js, MapLibre GL JS, deck.gl, Recharts; Python (NumPy, SciPy, h5py). Font: Hind Siliguri (SIL OFL).</li>
            <li>Team AlphaMatrix, NASA Space Apps Challenge 2026, challenge “Dancing with the SARs”. AI help is logged in docs/AI_USE.md.</li>
          </ul>
        </div>
      </main>
      <Footer />
    </>
  );
}
